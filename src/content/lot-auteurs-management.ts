export const carteAuteur = (c: Carte): Episode => ({
  id: c.id, ue: c.ue, notion: c.notion, format: "auteur", status: "live", minutes: 1,
  source: "Carte auteur Zenvise, programme DCG 2027",
  title: c.titre, ref: `${c.auteur}, ${c.date}`,
  scene: [N(c.situation), ...(c.question ? [D(c.question)] : [])],
  cours: [C(c.idee, true), C(`Le mot-clé à placer dans ta copie : ${c.motCle}.`, true), C(c.exemple), C(c.quand), C(c.limite)],
  flash: c.flash,
  fiche: {
    essentiel: c.idee,
    points: [`${c.auteur} (${c.date}).`, `Mot-clé : ${c.motCle}.`, c.exemple, c.quand, c.limite],
    methode: ["Partir de la situation", "Citer l'auteur et son concept", "Appliquer, puis nuancer avec la limite"],
    pieges: c.piege ? [c.piege] : undefined,
  },
});

const M = (c: Omit<Carte, "ue">) => carteAuteur({ ...c, ue: "dcg7" });

